// Regenerates src/catalog/basic/icons.js: SVG path data for the 61 A2UI basic catalog
// icon names, taken from Google's Material Symbols (Apache-2.0,
// github.com/google/material-design-icons). Name mapping matches @a2ui/web_core.
//
// Two steps, so downloads go through curl (which honours proxy settings):
//   node tools/fetch-icons.js --urls > tmp/icon-urls.txt
//   mkdir -p tmp/icons && (cd tmp/icons && xargs -n1 curl -sSfLO < ../icon-urls.txt)
//   node tools/fetch-icons.js tmp/icons
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import catalog from '../src/catalog/basic/catalog-json.js';

const REPO = 'https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web';
// Material Symbols differs from the older Material Icons set that web_core's names
// assume: outlined glyphs are the "off" look, filled ones live in *_fill1 files, and a
// few names were renamed.
const OVERRIDES = {
  play: 'play_arrow', rewind: 'fast_rewind',
  favorite: 'favorite_fill1', favoriteOff: 'favorite',
  star: 'star_fill1', starOff: 'star',
  payment: 'credit_card', phone: 'phone_enabled',
};
const toMaterial = name => OVERRIDES[name] ?? name.replace(/[A-Z]/g, c => `_${c.toLowerCase()}`);

const nameSchema = catalog.components.Icon.properties.name;
const names = (nameSchema.oneOf ?? nameSchema.anyOf ?? []).flatMap(s => s.enum ?? []);
if (names.length < 50) throw new Error(`expected ~61 icon names, found ${names.length}`);

const arg = process.argv[2];
if (arg === '--urls') {
  for (const name of names) {
    const mat = toMaterial(name);
    const dir = mat.replace(/_fill1$/, '');
    console.log(`${REPO}/${dir}/materialsymbolsoutlined/${mat}_24px.svg`);
  }
  process.exit(0);
}
if (!arg) { console.error('usage: node tools/fetch-icons.js --urls | <dir-with-svgs>'); process.exit(2); }

const icons = {};
const missing = [];
for (const name of names) {
  const file = path.join(arg, `${toMaterial(name)}_24px.svg`);
  if (!existsSync(file)) { missing.push(`${name}: ${file} not found`); continue; }
  const d = [...readFileSync(file, 'utf8').matchAll(/\sd="([^"]+)"/g)].map(m => m[1]);
  if (!d.length) { missing.push(`${name}: no path`); continue; }
  icons[name] = d.join(' ');
}
const body = Object.entries(icons).map(([k, v]) => `  ${k}: '${v}',`).join('\n');
writeFileSync(new URL('../src/catalog/basic/icons.js', import.meta.url), `// GENERATED by tools/fetch-icons.js. Do not edit by hand.
// Material Symbols (Outlined, 24px) path data, Copyright Google LLC, Apache-2.0.
// Source: https://github.com/google/material-design-icons  See NOTICE.
// All paths use the Material Symbols viewBox "0 -960 960 960".
export const ICON_VIEWBOX = '0 -960 960 960';
export const ICONS = {
${body}
};
`);
console.log(`wrote ${Object.keys(icons).length}/${names.length} icons`);
if (missing.length) { console.log('missing:\n  ' + missing.join('\n  ')); process.exitCode = 1; }
