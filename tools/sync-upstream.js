// Regenerates src/catalog/basic/catalog-json.js from the pinned upstream basic catalog.
// The catalog is shipped as a JS module (not a .json import) so it loads in every
// browser and Node version without import attributes.
//
//   node tools/sync-upstream.js
//
// Source of truth: test/upstream/basic_catalog_v1.json (copied from a2ui-project/a2ui
// at the commit recorded in test/upstream/PINNED_COMMIT, Apache-2.0).
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const catalog = JSON.parse(readFileSync(new URL('test/upstream/basic_catalog_v1.json', root), 'utf8'));
const commit = readFileSync(new URL('test/upstream/PINNED_COMMIT', root), 'utf8').trim();

const out = `// GENERATED by tools/sync-upstream.js. Do not edit by hand.
// A2UI v1.0 basic catalog, from github.com/a2ui-project/a2ui @ ${commit}
// Copyright Google LLC, Apache-2.0. See NOTICE.
export default ${JSON.stringify(catalog, null, 1)};
`;
writeFileSync(new URL('src/catalog/basic/catalog-json.js', root), out);
console.log(`wrote src/catalog/basic/catalog-json.js (${Object.keys(catalog.components).length} components, ${Object.keys(catalog.functions ?? {}).length} functions)`);

// Index of the upstream basic catalog examples, for the playground's preset menu.
const exDir = new URL('test/upstream/examples/', root);
const index = readdirSync(exDir).filter(f => f.endsWith('.json')).sort().map(file => {
  const ex = JSON.parse(readFileSync(new URL(file, exDir), 'utf8'));
  return { file, name: ex.name ?? file.replace(/\.json$/, ''), description: ex.description ?? '' };
});
mkdirSync(new URL('pages/data/', root), { recursive: true });
writeFileSync(new URL('pages/data/upstream-examples.json', root), `${JSON.stringify({ commit, source: 'https://github.com/a2ui-project/a2ui/tree/main/catalogs/basic/v1/examples', license: 'Apache-2.0', examples: index }, null, 1)}\n`);
console.log(`wrote pages/data/upstream-examples.json (${index.length} examples)`);
