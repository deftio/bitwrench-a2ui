// Generate docs/conformance-report.md from an actual conformance run.
//   node tools/conformance-report.js
// Runs the upstream suites with the executed-case manifest enabled, then maps every case
// to the renderer feature ids (F-RND-*) declared in the pinned conformance/features.yaml.
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestDir = path.join(root, 'tmp', 'conformance-manifest');
rmSync(manifestDir, { recursive: true, force: true });
mkdirSync(manifestDir, { recursive: true });

const run = spawnSync(process.execPath, ['--no-warnings', '--test', 'test/conformance/conformance.test.js'], {
  cwd: root, env: { ...process.env, A2UI_CONFORMANCE_MANIFEST_DIR: manifestDir }, encoding: 'utf8',
});
const records = readdirSync(manifestDir).flatMap(f => readFileSync(path.join(manifestDir, f), 'utf8').trim().split('\n').filter(Boolean).map(l => JSON.parse(l)));

const suites = {
  'core/adapter_conformance.yaml': 'test/upstream/conformance/adapter_conformance.yaml',
  'core/accessibility.yaml': 'test/upstream/conformance/accessibility.yaml',
  'adapter/markdown_subset.yaml': 'test/upstream/conformance/markdown_subset.yaml',
};
const caseFeatures = new Map();
for (const [suite, file] of Object.entries(suites)) {
  for (const c of parse(readFileSync(path.join(root, file), 'utf8'))) caseFeatures.set(`${suite}#${c.name}`, c.features ?? []);
}
const features = parse(readFileSync(path.join(root, 'test/upstream/conformance/features.yaml'), 'utf8'))
  .filter(f => typeof f.id === 'string' && f.id.startsWith('F-RND-'));

// Renderer features with no case in the pinned adapter suites, covered elsewhere or out of scope.
const NOTES = {
  'F-RND-10': 'Covered by unit tests: an agent-function binding renders while pending and re-renders with the response (test/unit/renderer.test.js, "agent functions route through callAgentFunction and resolve").',
  'F-RND-18': 'Not applicable: this renderer supports A2UI v1.0 only.',
  'F-RND-20': 'Not applicable: Universal Custom Elements interop concerns the Lit, React and Angular renderers.',
};

const bySuite = {};
for (const r of records) {
  const s = (bySuite[r.suite] ||= { passed: 0, failed: 0, skipped: 0 });
  s[r.status] = (s[r.status] ?? 0) + 1;
}

const rows = features.map(f => {
  const cases = records.filter(r => (caseFeatures.get(`${r.suite}#${r.case}`) ?? []).includes(f.id));
  const passed = cases.filter(c => c.status === 'passed').length;
  const na = NOTES[f.id]?.startsWith('Not applicable');
  // A not-applicable feature is never claimed, even if cases tagged with it pass.
  const status = na ? 'n/a' : cases.length === 0 ? 'unit tests' : passed === cases.length ? 'pass' : 'FAIL';
  const list = cases.map(c => `\`${c.case}\``).join(', ');
  const detail = na ? `${NOTES[f.id]}${cases.length ? ` (Tagged v1.0 cases ${list} pass, but the feature itself is not claimed.)` : ''}`
    : cases.length ? list : (NOTES[f.id] ?? 'No case in the pinned suites.');
  return `| ${f.id} | ${f.title.replace(/\s+/g, ' ').replace(/\|/g, '\\|')} | ${status} | ${detail} |`;
});

const pins = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8')).dependencies;
const commit = readFileSync(path.join(root, 'test/upstream/PINNED_COMMIT'), 'utf8').trim();
const md = `# Conformance report

This report is generated by \`node tools/conformance-report.js\` from a run of the pinned upstream A2UI conformance suites against bitwrench-a2ui. Do not edit it by hand.

* **Generated** - ${new Date().toISOString().slice(0, 10)}
* **Protocol** - A2UI v1.0
* **Suites** - \`a2ui-project/a2ui@${commit.slice(0, 8)}\` (pinned copies in \`test/upstream/conformance/\`)
* **Core** - \`@a2ui/web_core\` ${pins['@a2ui/web_core']}, rendering with bitwrench ${pins.bitwrench}
* **Harness** - \`test/conformance/\`, jsdom, modelled on the official Lit renderer harness. The executed-case manifest uses the upstream format (\`A2UI_CONFORMANCE_MANIFEST_DIR\`).
* **Test run** - ${run.status === 0 ? 'passed' : 'FAILED'}

## Suites

The results of the run, per suite:

| Suite | Passed | Failed | Skipped |
|---|---|---|---|
${Object.entries(bySuite).map(([s, v]) => `| \`conformance/${s}\` | ${v.passed} | ${v.failed} | ${v.skipped} |`).join('\n')}

## Renderer features

Each renderer feature id from \`conformance/features.yaml\`, with the cases that exercise it:

| Feature | Title | Status | Evidence |
|---|---|---|---|
${rows.join('\n')}

## Also tested

Beyond the conformance suites:

* **Golden examples** - all 43 upstream basic catalog examples render live and as static HTML with no errors (\`test/golden/\`).
* **Unit tests** - 100% line, branch, function and statement coverage of \`src/\` (\`npm run test:coverage\`).
* **Browser builds** - the dist files, the example pages and the site pages load and render in a page with no bundler (\`test/dist/\`).
`;
writeFileSync(path.join(root, 'docs', 'conformance-report.md'), md);
console.log(`wrote docs/conformance-report.md (${records.length} cases, run ${run.status === 0 ? 'passed' : 'FAILED'})`);
process.exitCode = run.status === 0 ? 0 : 1;
